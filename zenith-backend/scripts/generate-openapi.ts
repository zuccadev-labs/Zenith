import { join } from "@std/path";

// Minimal definition to type the manifest
interface BarritsBuildManifest {
  traitDescriptors: Array<{
    name: string;
    summary?: string;
    tags: string[];
  }>;
}

const BARRITS_DIR = ".barrits";
const MANIFEST_FILE = "build-manifest.json";

export const generateOpenApiSchema = (
  manifest: BarritsBuildManifest,
  options: { title?: string; version?: string; description?: string } = {}
): Record<string, any> => {
  const openapi = {
    openapi: "3.1.0",
    info: {
      title: options.title ?? "Zenith BaaS API",
      version: options.version ?? "1.0.0",
      description: options.description ?? "Automatically generated by Barrits AST Discovery.",
    },
    paths: {} as Record<string, any>,
    components: {
      schemas: {} as Record<string, any>,
    },
  };

  for (const descriptor of manifest.traitDescriptors) {
    // Si la función de nube (Cloud Function) tiene tag 'http-endpoint' o en el nombre termina con 'Endpoint'
    if (descriptor.tags.includes("http-endpoint") || descriptor.name.toLowerCase().includes("endpoint")) {
      const pathName = descriptor.name.toLowerCase().replace(/endpoint$/, "");
      const path = pathName.startsWith("/") ? pathName : `/${pathName}`;
      
      openapi.paths[path] = {
        post: {
          summary: descriptor.summary ?? `Executes ${descriptor.name}`,
          operationId: descriptor.name,
          responses: {
            "200": {
              description: "Successful response",
            },
          },
        },
      };
    }
  }

  return openapi;
};

async function main() {
  console.log("Generando OpenAPI 3.1 Schema usando el manifiesto de Barrits...");

  try {
    // Primero, ejecutar barrits para generar/actualizar el manifiesto
    console.log("Ejecutando Barrits discovery...");
    const cmd = new Deno.Command("deno", {
      args: ["run", "-A", "--config", "deno.json", "jsr:@zuccadev-labs/barrits/cli", "build"],
      cwd: Deno.cwd(),
      stdout: "inherit",
      stderr: "inherit"
    });
    
    const status = await cmd.output();
    if (!status.success) {
      throw new Error("Barrits build falló al generar el manifiesto.");
    }

    const manifestPath = join(Deno.cwd(), BARRITS_DIR, MANIFEST_FILE);
    const manifestContent = await Deno.readTextFile(manifestPath);
    const manifest: BarritsBuildManifest = JSON.parse(manifestContent);

    const schema = generateOpenApiSchema(manifest, {
      title: "Zenith Core & SaaS API",
      version: "1.0.0"
    });

    await Deno.writeTextFile("./swagger.json", JSON.stringify(schema, null, 2));
    console.log("¡Éxito! OpenAPI schema generado en ./swagger.json basándose en barrits.config.ts");
  } catch (error) {
    console.error("Error generando OpenAPI:", error);
    Deno.exit(1);
  }
}

if (import.meta.main) {
  main();
}
