import { parseArgs } from "@std/cli/parse-args";
import { ensureDir } from "@std/fs/ensure-dir";
import { expandGlob } from "@std/fs/expand-glob";
import { join } from "@std/path";

const helpText = `
Zenith CLI - Orchestrator & AOT Compiler

Usage:
  deno run -A scripts/zen.ts <command> [options]

Commands:
  dev       Start Zenith in development mode with live reload.
            Watches cloud/, plugins/, and config files.
  compile   Generate an AOT standalone production binary.
`;

async function buildManifest() {
  console.log("🛠️  [Zenith Compiler] Starting AOT Discovery...");
  
  const pluginsGlob = "plugins/**/*.{ts,tsx}";
  const cloudGlob = "cloud/**/*.{ts,tsx}";
  
  const imports: string[] = [];
  let idCounter = 0;

  for await (const entry of expandGlob(pluginsGlob)) {
    if (entry.isFile) {
       imports.push(`import * as Plugin_${idCounter++} from "../../${entry.path.replace(/\\/g, "/")}";`);
    }
  }

  for await (const entry of expandGlob(cloudGlob)) {
    if (entry.isFile) {
       imports.push(`import * as Cloud_${idCounter++} from "../../${entry.path.replace(/\\/g, "/")}";`);
    }
  }

  const manifestContent = `
// AUTO-GENERATED BY ZENITH COMPILER (DO NOT EDIT)
// This file ensures that Deno Compile statically bundles all plugins and cloud code.

${imports.join("\n")}

export const GeneratedPlugins = {
    total: ${idCounter},
    loadedAt: Date.now()
};
`;

  await ensureDir("./src/.generated");
  await Deno.writeTextFile("./src/.generated/manifest.ts", manifestContent);
  console.log("✅ [Zenith Compiler] Manifest generated at src/.generated/manifest.ts");
}

async function runDev() {
  console.log("🚀 Starting Zenith in Dev Mode (Live Reload)...");
  
  // Ensure logs directory exists for Dev mode too
  await ensureDir("./logs");

  const cmd = new Deno.Command("deno", {
    args: [
      "run",
      "--allow-net",
      "--allow-read",
      "--allow-env",
      "--allow-write",
      "--allow-sys",
      "--allow-ffi",
      "--unstable-ffi",
      "--unstable-kv",
      "--watch=cloud/,plugins/,apps.config.ts,barrits.config.ts",
      "src/mod.ts",
      "--mode=development"
    ],
    cwd: Deno.cwd(),
    stdout: "inherit",
    stderr: "inherit"
  });

  const child = cmd.spawn();
  
  // Graceful shutdown handling
  Deno.addSignalListener("SIGINT", () => {
    console.log("🛑 Gracefully shutting down dev server...");
    child.kill("SIGINT");
    Deno.exit(0);
  });

  const status = await child.status;
  Deno.exit(status.code);
}

async function runCompile() {
  console.log("📦 Compiling Zenith AOT Production Binary...");
  
  await ensureDir("./logs");
  await buildManifest();

  // Run Barrits to generate manifest so it's included or ready
  console.log("🔍 Generating Barrits Manifest for AOT...");
  const barritsCmd = new Deno.Command("deno", {
    args: ["run", "-A", "--config", "deno.json", "jsr:@zuccadev-labs/barrits/cli", "build"],
    cwd: Deno.cwd(),
    stdout: "inherit",
    stderr: "inherit"
  });
  await barritsCmd.output();

  const cmd = new Deno.Command("deno", {
    args: [
      "compile",
      "--allow-net",
      "--allow-read",
      "--allow-env",
      "--allow-write",
      "--allow-sys",
      "--no-check",
      "--output",
      "bin/zenith-backend",
      "src/mod.ts",
      "--mode=production"
    ],
    cwd: Deno.cwd(),
    stdout: "inherit",
    stderr: "inherit"
  });

  const child = cmd.spawn();
  const status = await child.status;
  
  if (status.success) {
    console.log("✅ Build successful! Binary is at bin/zenith-backend");
  } else {
    console.error("❌ Build failed.");
  }
  
  Deno.exit(status.code);
}

async function main() {
  const args = parseArgs(Deno.args);
  const command = args._[0];

  switch (command) {
    case "dev":
      await runDev();
      break;
    case "compile":
      await runCompile();
      break;
    case "help":
    default:
      console.log(helpText);
      Deno.exit(command === "help" ? 0 : 1);
  }
}

if (import.meta.main) {
  main();
}
